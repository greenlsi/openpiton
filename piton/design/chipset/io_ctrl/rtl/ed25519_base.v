    input			iBanks,		// 0: LO -> HI, 1: HI -> LO
    
    input	[5:0]	iSrc1_op,
    input	[5:0]	iSrc2_op,
    input	[5:0]	iDst_op,
    
    input	[2:0]	iSrc1_addr,
    input	[2:0]	iSrc2_addr,
    input	[2:0]	iDst_addr,
    
    input			iDst_wren,
    
    output	[31:0]	oSrc1,
    output	[31:0]	oSrc2,
    
