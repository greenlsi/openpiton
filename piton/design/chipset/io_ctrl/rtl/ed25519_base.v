 always@(*) begin
	case(uop_data_opcode)
		5'd1: begin
			banks_src1_addr = mw_mover_x_addr;
			banks_src2_addr = {3{1'bX}};
			banks_dst_addr  = mw_mover_y_addr;
			banks_dst_wren  = mw_mover_y_wren;
