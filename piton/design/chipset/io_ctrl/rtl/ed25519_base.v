 assign mod_mul_b_din  = banks_src2_dout;
 assign mod_add_a_din  = banks_src1_dout;
 assign mod_add_b_din  = banks_src2_dout;
 assign mod_sub_a_din  = banks_src1_dout;
 assign mod_sub_b_din  = banks_src2_dout;
 
