						  (uop_data_opcode[2]) ? mod_sub_ab_addr : mod_mul_b_addr;
 assign banks_dst_addr  = (uop_data_opcode[0]) ? mw_mover_y_addr :
						  (uop_data_opcode[1]) ? mod_add_s_addr  :
						  (uop_data_opcode[2]) ? mod_sub_d_addr  : mod_mul_p_addr;
