			banks_src1_addr = mod_sub_ab_addr;
			banks_src2_addr = mod_sub_ab_addr;
			banks_dst_addr  = mod_sub_d_addr;
			banks_dst_wren  = mod_sub_d_wren;
			banks_dst_din   = mod_sub_d_dout;
