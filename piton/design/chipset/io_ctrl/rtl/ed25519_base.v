	{mod_add_n_bit_upper, mod_add_n_bit_lower1, mod_add_n_bit_lower0} <= mod_sub_n_bit_w;
 end
 
 always@(posedge iClk) begin
	if(mod_sub_n_addr_ne0)	mod_sub_n_bit_lower <= 1'b1;
	else					mod_sub_n_bit_lower <= 1'b0;
 end

 // uOP Trigger Logic
 always@(posedge iClk) begin
