module adder32_generic (
	input			iClk,	// clock
	input	[31:0]	iA,		// operand input
	input	[31:0]	iB,		// operand input
	output	[31:0]	oS,		// sum output
	input			iC,	// carry input
	output			oC	// carry output
);

 // Sum
 reg	[32:0]	s_int;
 wire	[32:0]	bb;
 
 assign bb = iB + iC;
 always@(posedge iClk) begin
	s_int <= {1'b0, iA} + bb;
 end

 // Output
 assign oS = s_int[31:0];
 assign oC = s_int[32];

endmodule
